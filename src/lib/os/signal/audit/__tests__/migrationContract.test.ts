import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const sql = readFileSync(resolve(process.cwd(), 'supabase/migration-drafts/20261029001000_website_audit_phase1.sql'), 'utf8')
it('keeps the new schema default-denied and disabled without replacing Quick Scan contracts', () => {
  expect(sql).toContain('creation_enabled BOOLEAN NOT NULL DEFAULT false')
  expect(sql).toContain('worker_enabled BOOLEAN NOT NULL DEFAULT false')
  expect(sql).toContain('coordination_enabled BOOLEAN NOT NULL DEFAULT false')
  expect(sql).toContain('page_limit BETWEEN 1 AND 100')
  expect(sql).toContain('a.page_limit <= 100')
  expect(sql).not.toMatch(/CREATE(?: OR REPLACE)? FUNCTION public\.(?:connect_website_signal_source|submit_website_analysis)/)
  expect(sql).not.toMatch(/ALTER TABLE public\.website_scans/)
  for (const table of ['website_audit_runtime', 'website_audits', 'website_audit_pages', 'website_crawl_hosts']) expect(sql).toContain(`ALTER TABLE public.${table} ENABLE ROW LEVEL SECURITY`)
})
it('fences both modes on the same host and retains host deadlines across release', () => {
  expect(sql).toContain('QUICK_COORDINATED_CLAIM_REQUIRED')
  expect(sql).toContain('QUICK_STALE_HOST_LEASE')
  expect(sql).toContain('QUICK_STALE_LEASE')
  expect(sql).toContain('h.not_before <= clock_timestamp() AND NOT h.blocked')
  expect(sql).toContain('v_h.not_before,v_h.next_allowed_at')
  expect(sql).toContain("not_before=greatest(not_before,coalesce((p_result->>'not_before')::timestamptz")
  expect(sql).not.toMatch(/(?:UPDATE|DELETE FROM) public\.signal_observations/)
})
it('does not exempt processing-to-processing writes and scopes claim proof to the RPC update', () => {
  expect(sql).not.toContain("IF TG_OP='UPDATE' AND OLD.status='processing' THEN RETURN NEW")
  expect(sql).toContain("q.lease_token::text=current_setting('alyoxa.quick_claim_token',true)")
  expect(sql).toContain("set_config('alyoxa.quick_claim_token',v_token::text,true)")
  expect(sql).toContain("set_config('alyoxa.quick_claim_token',coalesce(v_previous_token,''),true)")
})
it('contains fenced atomic observation and summary persistence rather than increment-only counters', () => {
  expect(sql).toContain('AUDIT_STALE_LEASE')
  expect(sql).toContain('FOR UPDATE SKIP LOCKED')
  expect(sql).toContain('v_p.last_result_token = p_lease_token')
  expect(sql).toContain('security_invoker=true')
  expect(sql).toContain('summary_observation_id IS NOT NULL')
  expect(sql).toContain('audit_observations_source_key UNIQUE (id, source_id)')
  expect(sql).toContain('keep_website_audit_identity')
})
it('guards PostgreSQL compatibility, definer ownership and schema trust before creating objects', () => {
  expect(sql).toContain("'server_version_num')::integer < 150000")
  expect(sql).toContain("current_user <> 'postgres'")
  expect(sql).toContain('AUDIT_REQUIRES_TRUSTED_PUBLIC_SCHEMA')
  expect(sql).toContain('AUDIT_DEPENDENCY_EXECUTE_MISSING')
  expect(sql).not.toContain('SET search_path = public, pg_temp')
  expect(sql.match(/SET search_path = pg_catalog, public, pg_temp/g)).toHaveLength(5)
  expect(sql).not.toMatch(/(?<!\$)\$(?!\$)/)
})
it('backs off summary failures and preserves crash-safe host spacing and redirect history', () => {
  expect(sql).toContain('a.next_finalize_at <= clock_timestamp()')
  expect(sql).toContain("'status','finalization_retry','code',SQLSTATE")
  expect(sql).toContain("interval '120 seconds' + crawl_delay_ms")
  expect(sql).toContain('v_p.redirect_history ? v_url')
  expect(sql).toContain("reason='redirect_alias'")
  expect(sql).toContain("'admission_budget_exhausted'")
  expect(sql).toContain("'measured_titles'")
})
